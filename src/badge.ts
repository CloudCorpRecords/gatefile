/**
 * Human-readable README badge snippet summarizing a repo's gates.
 * Commas and colons for separation, no dashes of any kind in the copy.
 */
import type { Gate, GatesFile } from "./types.js";

const KIND_LABEL: Record<string, string> = {
  assignment_required: "assignment required",
  claim_first: "comment before starting",
  discuss_first: "discuss before opening a PR",
  vouch_required: "vouch required",
  dco_required: "DCO sign off",
  cla_required: "CLA signature",
  collaborators_only: "collaborators only",
  issue_first: "issue required for every PR",
  no_direct_prs: "no direct PRs",
};

function icon(gate: Gate): string {
  return gate.severity === "blocker" ? "BLOCKER" : "note";
}

/** Render the badge markdown for a repo's extracted gates. */
export function renderBadge(repo: string, gates: GatesFile): string {
  const lines: string[] = [];
  lines.push(`## Contribution gates (${repo})`);
  lines.push("");
  if (gates.gates.length === 0) {
    lines.push("No hidden gates found: fork, branch, and open a PR like normal.");
  } else {
    for (const gate of gates.gates) {
      const label = KIND_LABEL[gate.kind] ?? gate.kind;
      lines.push(`- [${icon(gate)}] ${label}: "${gate.evidence}" (${gate.source})`);
    }
  }
  const conventions: string[] = [];
  if (gates.conventions.branchNaming) conventions.push(`Branch naming: "${gates.conventions.branchNaming}"`);
  if (gates.conventions.prTitleFormat) conventions.push(`PR title: "${gates.conventions.prTitleFormat}"`);
  if (gates.conventions.requiredChecks.length > 0) {
    conventions.push(`Checks: ${gates.conventions.requiredChecks.map((c) => `"${c}"`).join(", ")}`);
  }
  if (conventions.length > 0) {
    lines.push("");
    lines.push("**Conventions**");
    lines.push("");
    for (const c of conventions) lines.push(`- ${c}`);
  }
  lines.push("");
  lines.push("_Generated by [gatefile](https://github.com/CloudCorpRecords/gatefile)._");
  return lines.join("\n");
}
